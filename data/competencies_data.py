def get_competencies_data():
    """دریافت داده‌های شایستگی‌ها برای Seed کردن"""
    return COMPETENCIES_DATA


def get_competency_by_title(title):
    """دریافت شایستگی بر اساس عنوان"""
    for comp in COMPETENCIES_DATA:
        if comp["title"] == title:
            return comp
    return None


def get_competencies_by_category(category):
    """دریافت شایستگی‌های یک دسته"""
    return [comp for comp in COMPETENCIES_DATA if comp["category"] == category]


def get_categories():
    """دریافت لیست دسته‌بندی‌ها با تعداد شایستگی"""
    categories = {}
    for comp in COMPETENCIES_DATA:
        cat = comp["category"]
        if cat not in categories:
            categories[cat] = 0
        categories[cat] += 1
    
    category_names = {
        "emotional": "عاطفی-هیجانی",
        "social": "اجتماعی",
        "educational": "آموزشی",
        "moral": "اخلاقی",
        "self_management": "خودمدیریتی",
        "participation": "مشارکت",
    }
    
    return {category_names.get(cat, cat): count for cat, count in categories.items()}